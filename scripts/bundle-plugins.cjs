#!/usr/bin/env node
'use strict';

/**
 * 把本地插件入口打成单文件 CJS。目录由参数决定，脚本本身不含平台语义。
 * 用法：node scripts/bundle-plugins.cjs [pluginsRoot]
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const esbuild = require('esbuild');

const root = path.resolve(__dirname, '..');
process.chdir(root);
const pluginsRoot = path.resolve(process.argv[2] || 'MusicBridge/local-plugins');
const selected = process.argv[3] ? new Set(process.argv[3].split(',').filter(Boolean)) : null;

async function main() {
    if (!fs.existsSync(pluginsRoot)) {
        console.log('No plugin directory: ' + pluginsRoot);
        return;
    }
    let count = 0;
    for (const entry of fs.readdirSync(pluginsRoot, { withFileTypes: true })) {
        if (!entry.isDirectory()) {
            continue;
        }
        if (selected && !selected.has(entry.name)) {
            continue;
        }
        const directory = path.join(pluginsRoot, entry.name);
        const manifestFile = path.join(directory, 'manifest.json');
        if (!fs.existsSync(manifestFile)) {
            continue;
        }
        const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
        const sourceEntry = manifest.runtime?.sourceEntry || manifest.entry.file;
        const entryFile = path.join(directory, sourceEntry);
        if (!fs.existsSync(entryFile)) {
            throw new Error('Plugin entry missing: ' + entryFile);
        }
        const outfile = path.join(directory, 'plugin.cjs');
        const pluginBuild = fs.existsSync(path.join(directory, 'build.cjs'))
            ? require(path.join(directory, 'build.cjs'))
            : null;
        await esbuild.build({
            entryPoints: [entryFile],
            outfile,
            bundle: true,
            platform: 'node',
            format: 'cjs',
            target: 'node18',
            logLevel: 'warning',
            logOverride: { 'require-resolve-not-external': 'silent' },
            plugins: pluginBuild?.plugins || [],
            banner: {
                js: '// Generated by scripts/bundle-plugins.cjs; do not edit.',
            },
        });
        const syncWorker = path.join(directory, 'node_modules/jsdom/lib/jsdom/living/xhr/xhr-sync-worker.js');
        if (fs.existsSync(syncWorker)) {
            await esbuild.build({
                entryPoints: [syncWorker],
                outfile: path.join(directory, 'xhr-sync-worker.js'),
                bundle: true,
                platform: 'node',
                format: 'cjs',
                target: 'node18',
                logLevel: 'warning',
                logOverride: { 'require-resolve-not-external': 'silent' },
            });
        }
        const unblockModules = path.join(directory, 'unblock-modules.cjs');
        if (fs.existsSync(unblockModules)) {
            const source = fs.readFileSync(unblockModules, 'utf8');
            const names = [...source.matchAll(/^\s*'([^']+)':/gm)].map((match) => match[1]);
            for (const target of [path.join(directory, 'modules'), path.join(pluginsRoot, 'modules')]) {
                fs.mkdirSync(target, { recursive: true });
                for (const name of names) {
                    fs.writeFileSync(
                        path.join(target, name + '.js'),
                        '// Placeholder: implementation is bundled in plugin.cjs.\n',
                    );
                }
            }
        }
        manifest.entry = {
            file: 'plugin.cjs',
            sha256: crypto.createHash('sha256').update(fs.readFileSync(outfile)).digest('hex'),
            size: fs.statSync(outfile).size,
        };
        manifest.runtime = { ...(manifest.runtime || {}), bundled: true, sourceEntry };
        fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 4) + '\n');
        count += 1;
        console.log('plugin bundle: ' + path.relative(root, outfile));
    }
    console.log('bundled ' + count + ' plugin(s)');
    if (selected && count !== selected.size) {
        throw new Error('Requested plugins not found: ' + [...selected].join(','));
    }
}

main().catch((error) => {
    console.error(error.message);
    process.exit(1);
});
